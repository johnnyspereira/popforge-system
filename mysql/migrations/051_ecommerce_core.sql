CREATE TABLE IF NOT EXISTS commerce_categories (
  id CHAR(36) NOT NULL,
  account_id CHAR(36) NOT NULL,
  name VARCHAR(120) NOT NULL,
  slug VARCHAR(140) NOT NULL,
  description TEXT NULL,
  active BOOLEAN NOT NULL DEFAULT TRUE,
  sort_order INT NOT NULL DEFAULT 0,
  created_at DATETIME(3) NOT NULL DEFAULT CURRENT_TIMESTAMP(3),
  updated_at DATETIME(3) NOT NULL DEFAULT CURRENT_TIMESTAMP(3) ON UPDATE CURRENT_TIMESTAMP(3),
  PRIMARY KEY (id),
  UNIQUE KEY commerce_categories_slug_unique (account_id, slug),
  CONSTRAINT commerce_categories_account_fk FOREIGN KEY (account_id) REFERENCES accounts(id) ON DELETE CASCADE
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;

CREATE TABLE IF NOT EXISTS commerce_products (
  id CHAR(36) NOT NULL,
  account_id CHAR(36) NOT NULL,
  category_id CHAR(36) NULL,
  name VARCHAR(180) NOT NULL,
  slug VARCHAR(200) NOT NULL,
  description TEXT NULL,
  status ENUM('draft','active','archived') NOT NULL DEFAULT 'draft',
  product_type ENUM('ready_made','made_to_order','custom_quote') NOT NULL DEFAULT 'ready_made',
  customizable BOOLEAN NOT NULL DEFAULT FALSE,
  featured BOOLEAN NOT NULL DEFAULT FALSE,
  seo_title VARCHAR(180) NULL,
  seo_description VARCHAR(320) NULL,
  created_at DATETIME(3) NOT NULL DEFAULT CURRENT_TIMESTAMP(3),
  updated_at DATETIME(3) NOT NULL DEFAULT CURRENT_TIMESTAMP(3) ON UPDATE CURRENT_TIMESTAMP(3),
  PRIMARY KEY (id),
  UNIQUE KEY commerce_products_slug_unique (account_id, slug),
  KEY commerce_products_status_idx (account_id, status, updated_at),
  CONSTRAINT commerce_products_account_fk FOREIGN KEY (account_id) REFERENCES accounts(id) ON DELETE CASCADE,
  CONSTRAINT commerce_products_category_fk FOREIGN KEY (category_id) REFERENCES commerce_categories(id) ON DELETE SET NULL
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;

CREATE TABLE IF NOT EXISTS commerce_product_variants (
  id CHAR(36) NOT NULL,
  account_id CHAR(36) NOT NULL,
  product_id CHAR(36) NOT NULL,
  sku VARCHAR(100) NOT NULL,
  name VARCHAR(160) NOT NULL,
  material VARCHAR(80) NULL,
  color VARCHAR(80) NULL,
  size_label VARCHAR(80) NULL,
  price DECIMAL(12,2) NOT NULL DEFAULT 0,
  compare_at_price DECIMAL(12,2) NULL,
  weight_grams DECIMAL(12,3) NULL,
  stock_quantity DECIMAL(12,3) NOT NULL DEFAULT 0,
  track_stock BOOLEAN NOT NULL DEFAULT TRUE,
  active BOOLEAN NOT NULL DEFAULT TRUE,
  created_at DATETIME(3) NOT NULL DEFAULT CURRENT_TIMESTAMP(3),
  updated_at DATETIME(3) NOT NULL DEFAULT CURRENT_TIMESTAMP(3) ON UPDATE CURRENT_TIMESTAMP(3),
  PRIMARY KEY (id),
  UNIQUE KEY commerce_variants_sku_unique (account_id, sku),
  KEY commerce_variants_product_idx (product_id, active),
  CONSTRAINT commerce_variants_account_fk FOREIGN KEY (account_id) REFERENCES accounts(id) ON DELETE CASCADE,
  CONSTRAINT commerce_variants_product_fk FOREIGN KEY (product_id) REFERENCES commerce_products(id) ON DELETE CASCADE
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;

CREATE TABLE IF NOT EXISTS commerce_inventory_items (
  id CHAR(36) NOT NULL,
  account_id CHAR(36) NOT NULL,
  sku VARCHAR(100) NOT NULL,
  item_type ENUM('filament','packaging','consumable','finished_product') NOT NULL,
  name VARCHAR(180) NOT NULL,
  material VARCHAR(80) NULL,
  color VARCHAR(80) NULL,
  unit ENUM('gram','unit','milliliter','meter') NOT NULL DEFAULT 'unit',
  purchase_total DECIMAL(12,2) NOT NULL DEFAULT 0,
  purchased_quantity DECIMAL(12,3) NOT NULL DEFAULT 0,
  remaining_quantity DECIMAL(12,3) NOT NULL DEFAULT 0,
  low_stock_threshold DECIMAL(12,3) NOT NULL DEFAULT 0,
  supplier VARCHAR(160) NULL,
  active BOOLEAN NOT NULL DEFAULT TRUE,
  created_at DATETIME(3) NOT NULL DEFAULT CURRENT_TIMESTAMP(3),
  updated_at DATETIME(3) NOT NULL DEFAULT CURRENT_TIMESTAMP(3) ON UPDATE CURRENT_TIMESTAMP(3),
  PRIMARY KEY (id),
  UNIQUE KEY commerce_inventory_sku_unique (account_id, sku),
  KEY commerce_inventory_type_idx (account_id, item_type, active),
  CONSTRAINT commerce_inventory_account_fk FOREIGN KEY (account_id) REFERENCES accounts(id) ON DELETE CASCADE,
  CONSTRAINT commerce_inventory_purchase_check CHECK (purchase_total >= 0 AND purchased_quantity >= 0 AND remaining_quantity >= 0)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;

CREATE TABLE IF NOT EXISTS commerce_orders (
  id CHAR(36) NOT NULL,
  account_id CHAR(36) NOT NULL,
  contact_id CHAR(36) NULL,
  order_number BIGINT NOT NULL AUTO_INCREMENT,
  status ENUM('draft','pending_payment','paid','in_production','quality_check','ready_to_ship','shipped','delivered','cancelled','refunded') NOT NULL DEFAULT 'draft',
  channel ENUM('online_store','backoffice','whatsapp','custom_quote') NOT NULL DEFAULT 'online_store',
  currency CHAR(3) NOT NULL DEFAULT 'EUR',
  subtotal DECIMAL(12,2) NOT NULL DEFAULT 0,
  discount_total DECIMAL(12,2) NOT NULL DEFAULT 0,
  shipping_total DECIMAL(12,2) NOT NULL DEFAULT 0,
  tax_total DECIMAL(12,2) NOT NULL DEFAULT 0,
  total DECIMAL(12,2) NOT NULL DEFAULT 0,
  customer_email VARCHAR(320) NULL,
  customer_name VARCHAR(180) NULL,
  shipping_address JSON NULL,
  tracking_code VARCHAR(160) NULL,
  notes TEXT NULL,
  paid_at DATETIME(3) NULL,
  created_at DATETIME(3) NOT NULL DEFAULT CURRENT_TIMESTAMP(3),
  updated_at DATETIME(3) NOT NULL DEFAULT CURRENT_TIMESTAMP(3) ON UPDATE CURRENT_TIMESTAMP(3),
  PRIMARY KEY (id),
  UNIQUE KEY commerce_orders_number_unique (order_number),
  KEY commerce_orders_status_idx (account_id, status, created_at),
  KEY commerce_orders_contact_idx (account_id, contact_id, created_at),
  CONSTRAINT commerce_orders_account_fk FOREIGN KEY (account_id) REFERENCES accounts(id) ON DELETE CASCADE,
  CONSTRAINT commerce_orders_contact_fk FOREIGN KEY (contact_id) REFERENCES contacts(id) ON DELETE SET NULL
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;

CREATE TABLE IF NOT EXISTS commerce_order_items (
  id CHAR(36) NOT NULL,
  account_id CHAR(36) NOT NULL,
  order_id CHAR(36) NOT NULL,
  product_id CHAR(36) NULL,
  variant_id CHAR(36) NULL,
  sku VARCHAR(100) NULL,
  product_name VARCHAR(180) NOT NULL,
  quantity INT NOT NULL DEFAULT 1,
  unit_price DECIMAL(12,2) NOT NULL DEFAULT 0,
  line_total DECIMAL(12,2) NOT NULL DEFAULT 0,
  customization JSON NOT NULL,
  created_at DATETIME(3) NOT NULL DEFAULT CURRENT_TIMESTAMP(3),
  PRIMARY KEY (id),
  KEY commerce_order_items_order_idx (order_id),
  CONSTRAINT commerce_order_items_account_fk FOREIGN KEY (account_id) REFERENCES accounts(id) ON DELETE CASCADE,
  CONSTRAINT commerce_order_items_order_fk FOREIGN KEY (order_id) REFERENCES commerce_orders(id) ON DELETE CASCADE,
  CONSTRAINT commerce_order_items_product_fk FOREIGN KEY (product_id) REFERENCES commerce_products(id) ON DELETE SET NULL,
  CONSTRAINT commerce_order_items_variant_fk FOREIGN KEY (variant_id) REFERENCES commerce_product_variants(id) ON DELETE SET NULL,
  CONSTRAINT commerce_order_items_quantity_check CHECK (quantity > 0)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;

CREATE TABLE IF NOT EXISTS commerce_production_jobs (
  id CHAR(36) NOT NULL,
  account_id CHAR(36) NOT NULL,
  order_item_id CHAR(36) NULL,
  status ENUM('queued','preparing','printing','post_processing','quality_check','completed','failed') NOT NULL DEFAULT 'queued',
  printer_name VARCHAR(120) NULL,
  material_inventory_id CHAR(36) NULL,
  estimated_minutes INT NULL,
  actual_minutes INT NULL,
  estimated_grams DECIMAL(12,3) NULL,
  actual_grams DECIMAL(12,3) NULL,
  failure_reason TEXT NULL,
  started_at DATETIME(3) NULL,
  completed_at DATETIME(3) NULL,
  created_at DATETIME(3) NOT NULL DEFAULT CURRENT_TIMESTAMP(3),
  updated_at DATETIME(3) NOT NULL DEFAULT CURRENT_TIMESTAMP(3) ON UPDATE CURRENT_TIMESTAMP(3),
  PRIMARY KEY (id),
  KEY commerce_jobs_queue_idx (account_id, status, created_at),
  CONSTRAINT commerce_jobs_account_fk FOREIGN KEY (account_id) REFERENCES accounts(id) ON DELETE CASCADE,
  CONSTRAINT commerce_jobs_order_item_fk FOREIGN KEY (order_item_id) REFERENCES commerce_order_items(id) ON DELETE SET NULL,
  CONSTRAINT commerce_jobs_material_fk FOREIGN KEY (material_inventory_id) REFERENCES commerce_inventory_items(id) ON DELETE SET NULL
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;

CREATE TABLE IF NOT EXISTS commerce_price_calculations (
  id CHAR(36) NOT NULL,
  account_id CHAR(36) NOT NULL,
  product_id CHAR(36) NULL,
  created_by CHAR(36) NULL,
  name VARCHAR(180) NOT NULL,
  inputs JSON NOT NULL,
  breakdown JSON NOT NULL,
  cost_total DECIMAL(12,2) NOT NULL DEFAULT 0,
  suggested_price DECIMAL(12,2) NOT NULL DEFAULT 0,
  created_at DATETIME(3) NOT NULL DEFAULT CURRENT_TIMESTAMP(3),
  PRIMARY KEY (id),
  KEY commerce_price_product_idx (account_id, product_id, created_at),
  CONSTRAINT commerce_price_account_fk FOREIGN KEY (account_id) REFERENCES accounts(id) ON DELETE CASCADE,
  CONSTRAINT commerce_price_product_fk FOREIGN KEY (product_id) REFERENCES commerce_products(id) ON DELETE SET NULL,
  CONSTRAINT commerce_price_created_by_fk FOREIGN KEY (created_by) REFERENCES app_users(id) ON DELETE SET NULL
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;
